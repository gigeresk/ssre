import sys
sys.path.insert(0, '.')
from sarrmodel import Net

import torch
import torchvision
import numpy as np
from PIL import Image
from torchvision.transforms import ToTensor
import argparse

'''
Used this code to convert from Python Pytorch-trained model to TorchScript, usable in C++
Torch Script is a representation of a PyTorch model that can be understood, compiled and serialized by the Torch Script compiler
The C++ API may not be able to understand the .pth models generated by the Python trainer
See this for details https://pytorch.org/tutorials/advanced/cpp_export.html

Example usage
python3 ./util/to_torchscript.py  --model models/model_epoch_1.pth --input_image dataset/training/Borderlands2June9qHD30fps-054.png 

'''

def to_torchscript():
    parser = argparse.ArgumentParser(description='PyTorch Super Res Example')
    parser.add_argument('--model', type=str, required=True, help='model file to use')
    parser.add_argument('--input_image', type=str, required=True, help='input image to use to trace the original NN')
    opt = parser.parse_args()

    # An instance of your model.

    device = torch.device("cuda")# if opt.cuda else "cpu")

    # deserialize the model
    model = Net(upscale_factor=2).to(device)
    checkpoint = torch.load( opt.model )
    model.load_state_dict( checkpoint['model_state_dict'] )

    # need an input iamge to trace the model with
    img_to_tensor = ToTensor()
    img = Image.open(opt.input_image).convert('YCbCr')
    y, cb, cr = img.split()
    input_image = img_to_tensor(y).view(1, -1, y.size[1], y.size[0]).cuda()

    # Use torch.jit.trace to generate a torch.jit.ScriptModule via tracing.
    traced_script_module = torch.jit.trace(model, input_image)

    traced_modelfilename = "traced-script-module-witcher2x.pt"
   

    traced_script_module.save( traced_modelfilename )
    print("Wrote traced model {0} to file".format( traced_modelfilename) )

if __name__ == "__main__":
    to_torchscript()